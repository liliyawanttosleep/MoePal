"""角色定义：人设、嗓音、音色、粒子、台词。 Character definitions."""
from dataclasses import dataclass, field


@dataclass
class Character:
    id: str
    name: str
    short: str
    persona: str                 # 给模型的人设 / persona for the LLM
    voices: list                 # 候选声线，第一个是默认；用户可在菜单里试听切换
    agent: str                   # 这个角色对应的电脑端 AI 应用（显示用）
    timbre: str                  # sfx.py 里的音色族
    babble_hz: float             # “咿呀语”基频
    particles: dict = field(default_factory=dict)   # 角色专属粒子
    color: str = "#888888"
    backends: tuple = ("claude_cli",)
    fallback: dict = field(default_factory=dict)    # 缺失动作 → 替代动作
    lines: dict = field(default_factory=dict)
    tagline: str = ""
    story: str = ""                                  # 背景故事（档案窗口显示，也写进人设）
    profile: list = field(default_factory=list)      # [(项目, 内容)]


def V(label, voice, rate=0, pitch=0):
    return {"id": voice, "label": label, "engine": "edge", "voice": voice, "rate": rate, "pitch": pitch}


def Z(char, ref_voice, ref_text, ref_rate="+0%", ref_pitch="+0Hz", speed=1.0):
    """自然对话声线：ZipVoice 参考音色克隆（本地显卡）。参考音色见 voice.ensure_prompt。"""
    return {"id": f"zv-{char}", "label": "自然对话 · 本地显卡（推荐）", "engine": "zipvoice", "char": char,
            "ref_voice": ref_voice, "ref_text": ref_text, "ref_rate": ref_rate, "ref_pitch": ref_pitch,
            "speed": speed, "steps": 8, "rate": 0, "pitch": 0}


